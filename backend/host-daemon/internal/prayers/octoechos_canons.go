// RegisterCanonRoutes registers the /api/v1/prayers/canon endpoints
func RegisterCanonRoutes(mux *http.ServeMux) {
	mux.HandleFunc("/api/v1/prayers/canon", handleCanonDetail)
	mux.HandleFunc("/api/v1/prayers/canons", handleCanonList)
}

func handleCanonList(w http.ResponseWriter, r *http.Request) {
	type CanonSummary struct {
		ToneNumber int    `json:"tone_number"`
		ToneName   string `json:"tone_name"`
		Title      string `json:"title"`
		Poet       string `json:"poet"`
		OdeCount   int    `json:"ode_count"`
	}
	var summaries []CanonSummary
	for i := 1; i <= 8; i++ {
		c, ok := AnastasimoiCanons[i]
		if ok {
			summaries = append(summaries, CanonSummary{
				ToneNumber: c.ToneNumber,
				ToneName:   c.ToneName,
				Title:      c.Title,
				Poet:       c.Poet,
				OdeCount:   len(c.Odes),
			})
		}
	}
	w.Header().Set("Content-Type", "application/json; charset=utf-8")
	json.NewEncoder(w).Encode(map[string]interface{}{
		"title":   "Αναστάσιμοι Κανόνες των 8 Ήχων (Αγίου Ιωάννου του Δαμασκηνού)",
		"count":   len(summaries),
		"canons": summaries,
	})
}

func handleCanonDetail(w http.ResponseWriter, r *http.Request) {
	toneParam := r.URL.Query().Get("tone")
	toneNum := 1
	if toneParam != "" {
		n, err := strconv.Atoi(toneParam)
		if err == nil && n >= 1 && n <= 8 {
			toneNum = n
		}
	}
	canon, ok := AnastasimoiCanons[toneNum]
	if !ok {
		http.Error(w, `{"error":"canon not found"}`, http.StatusNotFound)
		return
	}
	w.Header().Set("Content-Type", "application/json; charset=utf-8")
	json.NewEncoder(w).Encode(canon)
}

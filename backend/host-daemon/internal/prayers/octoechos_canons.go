// CanonOde holds an individual ode of a liturgical canon
type CanonOde struct {
	OdeNumber   string   `json:"ode_number"`   // "Ωδή α'", "Ωδή γ'", etc.
	OdeTitle    string   `json:"ode_title"`    // Theme or biblical ode reference
	Eirmos      string   `json:"eirmos"`       // Ο Ειρμός
	Troparia    []string `json:"troparia"`     // Τα Τροπάρια με τους στίχους
	Theotokion  string   `json:"theotokion"`   // Το Θεοτοκίον της Ωδής
	Katavasia   string   `json:"katavasia"`    // Η Καταβασία (προαιρετική)
}

// LiturgicalCanon holds a complete 8/9-ode canon
type LiturgicalCanon struct {
	ToneNumber    int        `json:"tone_number"`
	ToneName      string     `json:"tone_name"`
	Title         string     `json:"title"`
	Poet          string     `json:"poet"`          // e.g., "Ποίημα Ιωάννου του Δαμασκηνού"
	Acrostic      string     `json:"acrostic"`      // Ακροστιχίς
	Odes          []CanonOde `json:"odes"`
	KontakionOde6 string     `json:"kontakion_ode6"`
	IkosOde6      string     `json:"ikos_ode6"`
}


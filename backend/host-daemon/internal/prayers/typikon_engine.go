// LiturgicalVariables encapsulates all calculated dynamic parts for a service
type LiturgicalVariables struct {
	Date          string
	Tone          string
	ToneNumber    int
	Period        string
	MovableCycle  string
	FeastName     string
	Fasting       FastingType
	Antiphon1     string
	Antiphon2     string
	Antiphon3     string
	Eisodikon     string
	Apolytikia    []string
	Kontakion     string
	TrisagionHymn string
	EpistleRef    string
	EpistleText   string
	GospelRef     string
	GospelText    string
	Katavasies    KatavasiaSet
	Megalynarion  string
	Koinonikon    string
	Apolysis      string
	SaintsNames   []string
}

// ResolveLiturgicalVariables computes all dynamic elements for any Gregorian date
func ResolveLiturgicalVariables(date time.Time) LiturgicalVariables {
	toneStr := GetOctoechosTone(date)
	toneNum := extractToneNumber(toneStr)
	period, movable := GetLiturgicalPeriod(date)
	fasting := CalculateFastingRule(date)
	menologion := GetDailySaints(int(date.Month()), date.Day())
	katavasies := GetSeasonalKatavasies(date)

	// Resurrection hymns for the tone
	resHymns, hasTone := OctoechosResurrectionData[toneNum]
	if !hasTone {
		resHymns = OctoechosResurrectionData[1]
	}

	isSunday := date.Weekday() == time.Sunday

	// Antiphons
	ant1 := "Ταις πρεσβείαις της Θεοτόκου, Σώτερ σώσον ημάς."
	ant2 := "Σώσον ημάς, Υιέ Θεού, ο αναστάς εκ νεκρών, ψάλλοντάς σοι, Αλληλούϊα."
	if !isSunday {
		ant2 = "Σώσον ημάς, Υιέ Θεού, ο εν Αγίοις θαυμαστός, ψάλλοντάς σοι, Αλληλούϊα."
	}
	ant3 := resHymns.Apolytikion
	if !isSunday && menologion.Apolytikion != "" {
		ant3 = menologion.Apolytikion
	}

	// Eisodikon
	eisodikon := "Δεύτε προσκυνήσωμεν και προσπέσωμεν Χριστώ. Σώσον ημάς, Υιέ Θεού, ο αναστάς εκ νεκρών, ψάλλοντάς σοι, Αλληλούϊα."
	if !isSunday {
		eisodikon = "Δεύτε προσκυνήσωμεν και προσπέσωμεν Χριστώ. Σώσον ημάς, Υιέ Θεού, ο εν Αγίοις θαυμαστός, ψάλλοντάς σοι, Αλληλούϊα."
	}

	// Apolytikia list
	var apolytikia []string
	if isSunday {
		apolytikia = append(apolytikia, fmt.Sprintf("Αναστάσιμον (%s):\n%s", resHymns.Tone, resHymns.Apolytikion))
	}
	if menologion.Apolytikion != "" {
		apolytikia = append(apolytikia, fmt.Sprintf("Της Εορτής (%s):\n%s", menologion.FeastName, menologion.Apolytikion))
	}
	for _, s := range menologion.Saints {
		if s.Apolytikion != "" && s.Apolytikion != menologion.Apolytikion {
			apolytikia = append(apolytikia, fmt.Sprintf("Του Αγίου (%s):\n%s", s.Name, s.Apolytikion))
		}
	}
	if len(apolytikia) == 0 {
		apolytikia = append(apolytikia, resHymns.Apolytikion)
	}

	// Kontakion
	kontakion := "Προστασία των Χριστιανών ακαταίσχυντε, μεσιτεία προς τον Ποιητήν αμετάθετε, μη παρίδης αμαρτωλών δεήσεων φωνάς, αλλά πρόφθασον ως αγαθή, εις την βοήθειαν ημών, των πιστώς κραυγαζόντων σοι· Τάχυνον εις πρεσβείαν, και σπεύσον εις ικεσίαν, η προστατεύουσα αεί, Θεοτόκε των τιμώντων σε."
	if menologion.Kontakion != "" {
		kontakion = menologion.Kontakion
	} else if isSunday {
		kontakion = resHymns.Kontakion
	}

	// Trisagion Hymn
	trisagion := "Άγιος ο Θεός, Άγιος Ισχυρός, Άγιος Αθάνατος, ελέησον ημάς. (εκ γ')\n\nΔόξα Πατρί και Υιώ και Αγίω Πνεύματι, και νυν και αεί και εις τους αιώνας των αιώνων. Αμήν.\nΆγιος Αθάνατος, ελέησον ημάς.\n\nΔύναμις· Άγιος ο Θεός, Άγιος Ισχυρός, Άγιος Αθάνατος, ελέησον ημάς."

	// Lectionary readings
	epistleRef := ""
	epistleText := ""
	gospelRef := ""
	gospelText := ""

	lectionary, err := loadLectionary()
	dateKey := date.Format("01-02")
	if err == nil {
		if day, exists := lectionary.Readings[dateKey]; exists {
			epistleRef = day.Epistle.Reference
			epistleText = day.Epistle.Text
			gospelRef = day.Gospel.Reference
			gospelText = day.Gospel.Text
		}
	}
	if epistleText == "" && menologion.Apostolos.Text != "" {
		epistleRef = menologion.Apostolos.Reference
		epistleText = menologion.Apostolos.Text
	}
	if gospelText == "" && menologion.Evangelion.Text != "" {
		gospelRef = menologion.Evangelion.Reference
		gospelText = menologion.Evangelion.Text
	}

	// Megalynarion (Axion Estin or Katavasia 9th ode)
	megalynarion := "Άξιον εστίν ως αληθώς, μακαρίζειν σε την Θεοτόκον, την αειμακάριστον και παναμώμητον, και Μητέρα του Θεού ημών. Την τιμιωτέραν των Χερουβείμ, και ενδοξοτέραν ασυγκρίτως των Σεραφείμ, την αδιαφθόρως Θεόν Λόγον τεκούσαν, την όντως Θεοτόκον, σε μεγαλύνομεν."
	if katavasies.ID != "theotokos_standard" && katavasies.Ode9 != "" {
		megalynarion = fmt.Sprintf("Ειρμός θ' Ωδής (%s):\n%s", katavasies.Name, katavasies.Ode9)
	}

	// Koinonikon
	koinonikon := "Αινείτε τον Κύριον εκ των ουρανών, αινείτε αυτόν εν τοις υψίστοις. Αλληλούϊα."
	if !isSunday {
		koinonikon = "Εις μνημόσυνον αιώνιον έσται δίκαιος. Αλληλούϊα."
	}

	// Apolysis with saints
	var saintNames []string
	for _, s := range menologion.Saints {
		saintNames = append(saintNames, s.Name)
	}
	saintsListStr := strings.Join(saintNames, ", ")
	if saintsListStr == "" {
		saintsListStr = "των Αγίων ενδόξων και πανευφήμων Αποστόλων"
	}

	resPrefix := "Ο αναστάς εκ νεκρών, "
	if !isSunday {
		resPrefix = ""
	}
	apolysis := fmt.Sprintf("%sΧριστός ο αληθινός Θεός ημών, πρεσβείαις της παναχράντου και παναμώμου αγίας αυτού Μητρός, δυνάμει του τιμίου και ζωοποιού Σταυρού, προστασίαις των τιμίων επουρανίων Δυνάμεων ασωμάτων, ικεσίαις του τιμίου ενδόξου Προφήτου Προδρόμου και Βαπτιστού Ιωάννου, των αγίων ενδόξων και καλλινίκων Μαρτύρων, των οσίων και θεοφόρων Πατέρων ημών, και πάντων των σήμερον μνημονευομένων Αγίων (%s), ελεήσαι και σώσαι ημάς, ως αγαθός και φιλάνθρωπος και ελεήμων Θεός.", resPrefix, saintsListStr)

	return LiturgicalVariables{
		Date:          date.Format("2006-01-02"),
		Tone:          toneStr,
		ToneNumber:    toneNum,
		Period:        period,
		MovableCycle:  movable,
		FeastName:     menologion.FeastName,
		Fasting:       fasting,
		Antiphon1:     ant1,
		Antiphon2:     ant2,
		Antiphon3:     ant3,
		Eisodikon:     eisodikon,
		Apolytikia:    apolytikia,
		Kontakion:     kontakion,
		TrisagionHymn: trisagion,
		EpistleRef:    epistleRef,
		EpistleText:   epistleText,
		GospelRef:     gospelRef,
		GospelText:    gospelText,
		Katavasies:    katavasies,
		Megalynarion:  megalynarion,
		Koinonikon:    koinonikon,
		Apolysis:      apolysis,
		SaintsNames:   saintNames,
	}
}

func extractToneNumber(toneStr string) int {
	if strings.Contains(toneStr, "Πλ. Α'") {
		return 5
	}
	if strings.Contains(toneStr, "Πλ. Β'") {
		return 6
	}
	if strings.Contains(toneStr, "Βαρύς") {
		return 7
	}
	if strings.Contains(toneStr, "Πλ. Δ'") {
		return 8
	}
	if strings.Contains(toneStr, "Α'") {
		return 1
	}
	if strings.Contains(toneStr, "Β'") {
		return 2
	}
	if strings.Contains(toneStr, "Γ'") {
		return 3
	}
	if strings.Contains(toneStr, "Δ'") {
		return 4
	}
	return 1
}

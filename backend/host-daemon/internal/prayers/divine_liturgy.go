func formatCanonOdes(odes []CanonOde) string {
	var parts []string
	for _, o := range odes {
		odeStr := fmt.Sprintf("%s (%s):\n\nὉ Εἱρμός:\n%s\n\n%s\n\nΘεοτοκίον:\n%s",
			o.OdeNumber,
			o.OdeTitle,
			o.Eirmos,
			strings.Join(o.Troparia, "\n\n"),
			o.Theotokion,
		)
		parts = append(parts, odeStr)
	}
	return strings.Join(parts, "\n\n— — —\n\n")
}


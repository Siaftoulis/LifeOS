func getCommemorationOptions(date time.Time, saintIdx int) ([]CommemorationOption, int, string, string, string, string) {
	menologion := GetDailySaints(int(date.Month()), date.Day())
	var commOptions []CommemorationOption
	if len(menologion.Saints) > 0 {
		for i, s := range menologion.Saints {
			commOptions = append(commOptions, CommemorationOption{
				Index: i,
				Name:  s.Name,
				Title: s.Title,
			})
		}
	} else {
		commOptions = append(commOptions, CommemorationOption{
			Index: 0,
			Name:  menologion.FeastName,
			Title: "Εκκλησιαστικό Ημερολόγιο",
		})
	}

	if saintIdx < 0 || saintIdx >= len(menologion.Saints) {
		saintIdx = 0
	}

	sName := menologion.FeastName
	sTitle := ""
	sApol := menologion.Apolytikion
	sKont := menologion.Kontakion
	if len(menologion.Saints) > 0 && saintIdx < len(menologion.Saints) {
		sName = menologion.Saints[saintIdx].Name
		sTitle = menologion.Saints[saintIdx].Title
		if menologion.Saints[saintIdx].Apolytikion != "" {
			sApol = menologion.Saints[saintIdx].Apolytikion
		}
		if menologion.Saints[saintIdx].Kontakion != "" {
			sKont = menologion.Saints[saintIdx].Kontakion
		}
	}
	return commOptions, saintIdx, sName, sTitle, sApol, sKont
}

